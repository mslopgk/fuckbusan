def _theme_stat_rows():
    """THEME_STATS + 구별 확보 지표(CCTV/교통사고/공공도서관) 행 생성."""
    rows = []
    order = 0
    for theme, region, metric, vtext, year, note, skey in THEME_STATS:
        order += 1
        rows.append((theme, region, metric, vtext, year, note, skey, order))
        # 부산 전체행 뒤에 구별 행 삽입 (같은 metric — overview 가 region 우선 선택)
        if metric == "방범용 CCTV" and region == "부산":
            for gu, n in CCTV_BY_GU.items():
                order += 1
                rows.append((theme, gu, metric, f"{n:,}대", "2025",
                             "생활방범 CCTV(2025.12.29 기준)", "cctv2", order))
        elif metric == "교통사고 발생" and region == "부산":
            for gu, _pop, acc, _d, _i, _l in DISTRICTS:
                order += 1
                note_gu = "부산 16개 구·군 중 최다" if gu == "부산진구" else None
                rows.append((theme, gu, metric, f"{acc:,}건", "2024", note_gu, "taas", order))
        elif metric == "공공도서관" and region == "부산":
            for gu, _pop, _a, _d, _i, lib in DISTRICTS:
                order += 1
                rows.append((theme, gu, metric, f"{lib}개관", "2024", None, "lib", order))
    return rows


def seed_public_data(db):
    """idempotent: 기존 행 비우고 실데이터 재적재 (참조 테이블, 소량)."""
    import models
    db.query(models.PublicDistrict).delete()
    db.query(models.PublicPopTrend).delete()
    db.query(models.PublicThemeStat).delete()
    db.query(models.PublicLayer).delete()

    for region, pop, acc, dth, inj, lib in DISTRICTS:
        db.add(models.PublicDistrict(region=region, population=pop, accidents=acc,
                                     acc_deaths=dth, acc_injuries=inj, libraries=lib))
    for year, val in POP_TREND:
        db.add(models.PublicPopTrend(region="부산광역시", year=year, value=val, source=SRC["pop"]))
    theme_rows = _theme_stat_rows()
    for theme, region, metric, vtext, year, note, skey, order in theme_rows:
        db.add(models.PublicThemeStat(theme=theme, region=region, metric=metric, value_text=vtext,
                                      year=year, note=note, source=SRC.get(skey), sort_order=order))
    for key, label, region, count, skey, order in LAYERS:
        db.add(models.PublicLayer(key=key, label=label, region=region, count=count,
                                  source=SRC.get(skey) if skey else None, sort_order=order))
    db.commit()
    return {
        "districts": len(DISTRICTS), "pop_trend": len(POP_TREND),
        "theme_stats": len(theme_rows), "layers": len(LAYERS),
    }
